export const CURRICULUM: Subject[] = [
  ...BASE_SUBJECTS.map((subject) => ({
    ...subject,
    sections: subject.sections.map((section) => {
      const enrich = SECTION_ENRICHMENTS[section.id];
      if (!enrich) return section;
      return {
        ...section,
        lecture: enrich.lecture,
        problems: enrich.extraPracticeProblems
          ? [...section.problems, ...enrich.extraPracticeProblems]
          : section.problems,
        testOutProblems: enrich.testOutProblems,
      };
    }),
  })),
  STATISTICS_SUBJECT,
];

export function getAllProblems() {
  return CURRICULUM.flatMap((subject) =>
    subject.sections.flatMap((section) =>
      section.problems.map((problem) => ({
        subject,
        section,
        problem,
      }))
    )
  );
}
